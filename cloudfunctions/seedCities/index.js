// 展平为有序数组 [{name, short, province}]，顺序即 rank 顺序。
function flatten() {
  const list = [];
  Object.keys(CITY_BY_PROVINCE).forEach(function (prov) {
    CITY_BY_PROVINCE[prov].forEach(function (name) {
      list.push({ name: name, short: name.replace(/市$/, ''), province: prov });
    });
  });
  return list;
}

function pad(n, len) { let s = String(n); while (s.length < len) s = '0' + s; return s; }

async function ensureCollection() {
  try { await db.createCollection(COLLECTION); } catch (e) { /* already exists */ }
}

exports.main = async (event) => {
  const { apply = true } = event || {};
  const cities = flatten();
  if (cities.length < MIN_ACCEPT) {
    return { success: false, error: `city list too short: ${cities.length} < ${MIN_ACCEPT}` };
  }
  if (!apply) {
    return { success: true, dryRun: true, count: cities.length };
  }

  await ensureCollection();
  const col = db.collection(COLLECTION);
  const now = new Date();
  let written = 0, failed = 0;

  // 用 doc(_id).set() 幂等 upsert：不存在则创建、存在则覆盖。
  // （微信云 doc().update() 对不存在的文档不会创建，会静默 updated:0，故不能用。）
  // 分批并发写入：338 条串行会超时（默认 3s），并发 25 一批几秒内写完。
  const BATCH = 25;
  for (let i = 0; i < cities.length; i += BATCH) {
    const slice = cities.slice(i, i + BATCH);
    const results = await Promise.all(slice.map((c, j) => {
      const idx = i + j;
      const _id = `${THEME}_${pad(idx + 1, 3)}`;
      const doc = { theme: THEME, rank: idx + 1, name: c.name, shortName: c.short, province: c.province, updateTime: now };
      return col.doc(_id).set({ data: doc }).then(() => true).catch(e => { console.error('seed city fail', _id, e); return false; });
    }));
    results.forEach(ok => { if (ok) written++; else failed++; });
  }

  return { success: failed === 0, total: cities.length, written, failed };
};
